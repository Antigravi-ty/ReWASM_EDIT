import os
import re
import sys
import subprocess
from concurrent.futures import ProcessPoolExecutor

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
ROOT_DIR = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
OUT_DIR = os.path.join(SCRIPT_DIR, "build")
OBJ_DIR = os.path.join(OUT_DIR, "obj")
BRIDGE_PATH = os.path.join(SCRIPT_DIR, "RocketSimBridge.cpp")
os.makedirs(OBJ_DIR, exist_ok=True)


def parse_bridge_exports(bridge_path):
    """
    Parse RocketSimBridge.cpp extern "C" block for EMSCRIPTEN_KEEPALIVE exports.
    Fail if any non-static physics_* function inside extern "C" is missing EMSCRIPTEN_KEEPALIVE.
    Returns list of dicts: [{"name": "physics_...", "ret_ts": "number"|"void", "params": [(pname, "number"), ...]}]
    """
    with open(bridge_path, "r", encoding="utf-8") as f:
        content = f.read()

    extern_idx = content.find('extern "C"')
    if extern_idx == -1:
        raise RuntimeError(f"Could not find extern \"C\" block in {bridge_path}")

    extern_body = content[extern_idx:]
    # Strip C/C++ comments for clean signature scanning
    clean_body = re.sub(r"//.*", "", extern_body)
    clean_body = re.sub(r"/\*.*?\*/", "", clean_body, flags=re.DOTALL)

    # Check for any non-static physics_* function missing EMSCRIPTEN_KEEPALIVE
    all_physics_fn_re = re.compile(
        r"(?P<prefix>(?:EMSCRIPTEN_KEEPALIVE\s+|static\s+)?)"
        r"(?P<ret>(?:const\s+)?(?:void|int|float|double|bool|uint32_t|uint16_t|uint8_t|int32_t|int16_t|int8_t|size_t)(?:\s*\*)?)\s+"
        r"(?P<name>physics_[a-zA-Z0-9_]+)\s*\((?P<params>[^)]*)\)\s*\{",
        re.MULTILINE,
    )

    exports = []
    missing_keepalive = []

    for m in all_physics_fn_re.finditer(clean_body):
        prefix = m.group("prefix").strip()
        ret_raw = m.group("ret").strip()
        fn_name = m.group("name").strip()
        params_raw = m.group("params").strip()

        if prefix == "static":
            continue
        if "EMSCRIPTEN_KEEPALIVE" not in prefix:
            missing_keepalive.append(fn_name)
            continue

        is_void_return = (ret_raw == "void")
        ret_ts = "void" if is_void_return else "number"

        params = []
        if params_raw and params_raw != "void":
            for idx, part in enumerate(params_raw.split(",")):
                part = part.strip()
                if not part:
                    continue
                # Extract parameter identifier at the end of the declaration
                tokens = re.findall(r"[a-zA-Z_][a-zA-Z0-9_]*", part)
                param_name = tokens[-1] if tokens else f"arg{idx}"
                params.append((param_name, "number"))

        exports.append({
            "name": fn_name,
            "ret_ts": ret_ts,
            "params": params,
        })

    if missing_keepalive:
        raise RuntimeError(
            "The following physics_* functions in extern \"C\" are missing EMSCRIPTEN_KEEPALIVE: "
            + ", ".join(missing_keepalive)
        )

    if not exports:
        raise RuntimeError("No EMSCRIPTEN_KEEPALIVE functions found in RocketSimBridge.cpp")

    return exports


def generate_core_dts(exports, dts_path):
    """
    Generate TypeScript declaration file (core.d.ts) from parsed C++ bridge signatures.
    """
    lines = [
        "/**",
        " * AUTO-GENERATED BY ReWASM_EDIT/wasm/compile.py — DO NOT EDIT MANUALLY.",
        " * TypeScript declaration for Emscripten-generated RocketSim WebAssembly module (core.js / core.wasm).",
        " * Derived directly from EMSCRIPTEN_KEEPALIVE signatures in ReWASM_EDIT/wasm/RocketSimBridge.cpp.",
        " */",
        "",
        "export interface RocketSimWasmModuleOptions {",
        "  freshInstance?: boolean;",
        "  isolated?: boolean;",
        "  locateFile?: (path: string, scriptDirectory: string) => string;",
        "  wasmBinary?: ArrayBuffer | Uint8Array;",
        "  [key: string]: unknown;",
        "}",
        "",
        "export interface RocketSimWasmModule {",
        "  HEAP8: Int8Array;",
        "  HEAPU8: Uint8Array;",
        "  HEAP16: Int16Array;",
        "  HEAPU16: Uint16Array;",
        "  HEAP32: Int32Array;",
        "  HEAPU32: Uint32Array;",
        "  HEAPF32: Float32Array;",
        "  HEAPF64: Float64Array;",
        "",
        "  ccall: (",
        "    ident: string,",
        "    returnType: string | null,",
        "    argTypes: string[],",
        "    args: unknown[]",
        "  ) => unknown;",
        "  cwrap: (",
        "    ident: string,",
        "    returnType: string | null,",
        "    argTypes: string[]",
        "  ) => (...args: unknown[]) => unknown;",
        "",
        "  _malloc(size: number): number;",
        "  _free(ptr: number): void;",
        "",
        "  // Emscripten C-prefixed exports (_physics_*)",
    ]

    for fn in exports:
        param_str = ", ".join(f"{pname}: {ptype}" for pname, ptype in fn["params"])
        lines.append(f"  _{fn['name']}({param_str}): {fn['ret_ts']};")

    lines.append("")
    lines.append("  // Semantic unprefixed aliases bound by RocketSimWasm.ts")
    for fn in exports:
        lines.append(f"  {fn['name']}: RocketSimWasmModule['_{fn['name']}'];")

    lines.extend([
        "",
        "  [key: string]: any;",
        "}",
        "",
        "declare function loadDirectRocketSimWasm(",
        "  options?: RocketSimWasmModuleOptions",
        "): Promise<RocketSimWasmModule>;",
        "",
        "export default loadDirectRocketSimWasm;",
        "",
    ])

    with open(dts_path, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))


bridge_exports = parse_bridge_exports(BRIDGE_PATH)
print(f"Discovered {len(bridge_exports)} EMSCRIPTEN_KEEPALIVE exports in RocketSimBridge.cpp")

sources = []
for base in [os.path.join(ROOT_DIR, "libsrc", "bullet3-3.24"), os.path.join(ROOT_DIR, "src")]:
    for root, dirs, files in os.walk(base):
        for f in files:
            if f.endswith(".cpp"):
                sources.append(os.path.join(root, f))
sources.append(BRIDGE_PATH)

common_flags = [
    "-std=c++20",
    "-O3",
    "-fno-fast-math",
    "-fno-associative-math",
    "-DNDEBUG",
    "-g2",
    f"-I{os.path.join(ROOT_DIR, 'src')}",
    f"-I{os.path.join(ROOT_DIR, 'libsrc', 'bullet3-3.24')}"
]


def compile_file(src):
    rel = os.path.relpath(src, ROOT_DIR).replace("/", "_").replace("\\", "_") + ".o"
    obj = os.path.join(OBJ_DIR, rel)
    cmd = ["em++"] + common_flags + ["-c", src, "-o", obj]
    res = subprocess.run(cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"Error compiling {src}:\n{res.stderr}")
        return False
    return True


if __name__ == "__main__":
    print(f"Compiling {len(sources)} files with {os.cpu_count()} workers...")
    with ProcessPoolExecutor(max_workers=os.cpu_count()) as executor:
        results = list(executor.map(compile_file, sources))

    if not all(results):
        print("Compilation failed!")
        sys.exit(1)

    print("All object files compiled successfully! Linking...")

    objs = [os.path.join(OBJ_DIR, f) for f in os.listdir(OBJ_DIR) if f.endswith(".o")]

    export_names = ["_malloc", "_free"] + [f"_{fn['name']}" for fn in bridge_exports]
    exported_functions = "[" + ",".join(f"'{name}'" for name in export_names) + "]"

    exported_runtime_methods = (
        "['ccall','cwrap','HEAP8','HEAPU8','HEAP16','HEAPU16','HEAP32','HEAPU32','HEAPF32','HEAPF64']"
    )

    link_cmd = [
        "em++",
        "-std=c++20",
        "-O3",
        "-fno-fast-math",
        "-fno-associative-math",
        "-DNDEBUG",
        "-g2",
        "-sFILESYSTEM=0",
        "-sUSE_CLOSURE_COMPILER=0",
        "-sENVIRONMENT=web,node,worker",
        "-sMODULARIZE=1",
        "-sEXPORT_ES6=1",
        '-sEXPORT_NAME="loadDirectRocketSimWasm"',
        "-sALLOW_MEMORY_GROWTH=1",
        "-sINITIAL_MEMORY=67108864",
        f"-sEXPORTED_FUNCTIONS={exported_functions}",
        f"-sEXPORTED_RUNTIME_METHODS={exported_runtime_methods}",
        "-o", os.path.join(OUT_DIR, "core.js")
    ] + objs

    res = subprocess.run(link_cmd, capture_output=True, text=True)
    if res.returncode != 0:
        print(f"Linking error:\n{res.stderr}")
        sys.exit(1)

    dts_out = os.path.join(OUT_DIR, "core.d.ts")
    generate_core_dts(bridge_exports, dts_out)

    print(
        f"Successfully generated {os.path.join(OUT_DIR, 'core.wasm')}, "
        f"{os.path.join(OUT_DIR, 'core.js')}, and {dts_out} ({len(bridge_exports)} exports)!"
    )
